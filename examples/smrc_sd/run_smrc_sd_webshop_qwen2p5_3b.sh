export PATH_STATE_MATCH_CONTEXT=recovery
export PATH_RECOVERY_PROMPT_STYLE=state_summary_candidate
export PATH_RECOVERY_GUIDANCE_STYLE=path_on_or_off
export PATH_SDL_SAMPLE_FILTER=all
